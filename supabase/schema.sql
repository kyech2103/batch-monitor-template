-- 지금 로그인한 사용자의 직원 id (등록되지 않았으면 NULL)
CREATE OR REPLACE FUNCTION public.current_worker_id() RETURNS BIGINT
LANGUAGE sql STABLE SECURITY DEFINER SET search_path = '' AS $$
  SELECT w.id FROM public.workers w
  WHERE lower(w.email) = lower(auth.jwt() ->> 'email') AND w.status = '사용'
  LIMIT 1;
$$;

CREATE OR REPLACE FUNCTION public.is_active_worker() RETURNS BOOLEAN
LANGUAGE sql STABLE SET search_path = '' AS $$
  SELECT public.current_worker_id() IS NOT NULL;
$$;

