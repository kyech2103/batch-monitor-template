-- 규칙 전체 교체 (화면의 할 일 규칙 편집기가 부른다)
CREATE OR REPLACE FUNCTION public.replace_todo_rules(p_rules jsonb, p_updated_by text DEFAULT NULL)
RETURNS integer LANGUAGE plpgsql SET search_path = '' AS $$
DECLARE v_count integer := 0;
BEGIN
  DELETE FROM public.todo_rules WHERE true;
  IF p_rules IS NOT NULL AND jsonb_array_length(p_rules) > 0 THEN
    INSERT INTO public.todo_rules (rule_id, kind, enabled, title, process_code, anchor_step, anchor_point, day_rule,
      time_mode, target_time, offset_minutes, roles, holiday_check, sort_order, updated_at, updated_by)
    SELECT r->>'rule_id', 'SIMPLE', COALESCE((r->>'enabled')::boolean, true), r->>'title', r->>'process_code',
      r->>'anchor_step', r->>'anchor_point', r->>'day_rule', r->>'time_mode', r->>'target_time',
      COALESCE((r->>'offset_minutes')::integer, 0), ARRAY(SELECT jsonb_array_elements_text(r->'roles')),
      COALESCE((r->>'holiday_check')::boolean, true), COALESCE((r->>'sort_order')::integer, 100), now(), p_updated_by
    FROM jsonb_array_elements(p_rules) AS r;
    GET DIAGNOSTICS v_count = ROW_COUNT;
  END IF;
  RETURN v_count;
END;
$$;

-- 생성된 할 일 전체 교체 (공휴일 행은 그대로)
CREATE OR REPLACE FUNCTION public.replace_todo_schedules(p_rows jsonb, p_generated_at timestamptz DEFAULT now())
RETURNS integer LANGUAGE plpgsql SET search_path = '' AS $$
DECLARE v_count integer := 0;
BEGIN
  DELETE FROM public.todo_schedules WHERE record_type = 'TODO';
  IF p_rows IS NOT NULL AND jsonb_array_length(p_rows) > 0 THEN
    INSERT INTO public.todo_schedules (record_type, target_date, target_time, role_key, worker_name, lot_id, lot_ids,
      process_code, rule_id, task_key, title, generated_at)
    SELECT 'TODO', (r->>'target_date')::date, r->>'target_time', r->>'role_key', r->>'worker_name', r->>'lot_id',
      CASE WHEN jsonb_typeof(r->'lot_ids') = 'array' THEN ARRAY(SELECT jsonb_array_elements_text(r->'lot_ids')) END,
      r->>'process_code', r->>'rule_id', r->>'task_key', r->>'title', COALESCE(p_generated_at, now())
    FROM jsonb_array_elements(p_rows) AS r;
    GET DIAGNOSTICS v_count = ROW_COUNT;
  END IF;
  RETURN v_count;
END;
$$;

