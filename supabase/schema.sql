-- 할 일의 담당자 이름 → 직원 id (알림 발송용)
CREATE OR REPLACE FUNCTION public.set_todo_schedule_worker_id() RETURNS TRIGGER
LANGUAGE plpgsql SET search_path = '' AS $$
BEGIN
  IF NEW.worker_name IS NOT NULL THEN
    SELECT id INTO NEW.worker_id FROM public.workers WHERE name = NEW.worker_name AND status = '사용' LIMIT 1;
  ELSE
    NEW.worker_id := NULL;
  END IF;
  RETURN NEW;
END;
$$;
DROP TRIGGER IF EXISTS trg_set_todo_schedule_worker_id ON public.todo_schedules;
CREATE TRIGGER trg_set_todo_schedule_worker_id
BEFORE INSERT OR UPDATE OF worker_name ON public.todo_schedules
FOR EACH ROW EXECUTE FUNCTION public.set_todo_schedule_worker_id();

