CREATE OR REPLACE FUNCTION public.admin_add_worker(p_name TEXT, p_department TEXT, p_email TEXT)
RETURNS BIGINT LANGUAGE plpgsql SECURITY DEFINER SET search_path = '' AS $$
DECLARE v_name TEXT := btrim(coalesce(p_name, '')); v_email TEXT := lower(btrim(coalesce(p_email, ''))); v_id BIGINT;
BEGIN
  PERFORM public.assert_admin();
  IF v_name = '' OR char_length(v_name) > 30 THEN RAISE EXCEPTION '이름을 확인해 주세요'; END IF;
  IF v_email !~ '^[^@\s]+@[^@\s]+\.[^@\s]+$' THEN RAISE EXCEPTION '이메일을 확인해 주세요'; END IF;
  -- 할 일 배정이 이름으로 연결되므로 이름 중복 금지
  IF EXISTS (SELECT 1 FROM public.workers WHERE name = v_name) THEN RAISE EXCEPTION '같은 이름의 직원이 이미 있습니다'; END IF;
  IF EXISTS (SELECT 1 FROM public.workers WHERE lower(email) = v_email) THEN RAISE EXCEPTION '같은 이메일의 직원이 이미 있습니다'; END IF;
  INSERT INTO public.workers (name, department, email) VALUES (v_name, nullif(btrim(coalesce(p_department, '')), ''), v_email)
  RETURNING id INTO v_id;
  RETURN v_id;
END;
$$;

-- 쉼표 목록에서 이름 하나 빼기 ('홍길동, 김철수' - 김철수 → '홍길동')
CREATE OR REPLACE FUNCTION public.remove_name_from_list(p_list TEXT, p_name TEXT) RETURNS TEXT
LANGUAGE sql IMMUTABLE SET search_path = '' AS $$
  SELECT coalesce(string_agg(t.n, ', ' ORDER BY t.ord), '')
  FROM (SELECT btrim(raw) AS n, ord FROM unnest(string_to_array(coalesce(p_list, ''), ',')) WITH ORDINALITY AS u(raw, ord)) t
  WHERE t.n <> '' AND t.n <> p_name;
$$;

-- 직원 삭제: 알림 구독은 함께 지워지고, 담당자 칸에서 이름이 빠진다
CREATE OR REPLACE FUNCTION public.admin_retire_worker(p_worker_id BIGINT)
RETURNS VOID LANGUAGE plpgsql SECURITY DEFINER SET search_path = '' AS $$
DECLARE v_admin BIGINT := public.assert_admin(); v_name TEXT; v_is_admin BOOLEAN; v_is_owner BOOLEAN;
BEGIN
  IF p_worker_id = v_admin THEN RAISE EXCEPTION '자기 자신은 삭제할 수 없습니다'; END IF;
  SELECT name, is_admin, is_owner INTO v_name, v_is_admin, v_is_owner FROM public.workers WHERE id = p_worker_id;
  IF v_name IS NULL THEN RAISE EXCEPTION '없는 직원입니다'; END IF;
  IF v_is_owner THEN RAISE EXCEPTION '1차 관리자는 삭제할 수 없습니다'; END IF;
  IF v_is_admin AND NOT EXISTS (SELECT 1 FROM public.workers WHERE id = v_admin AND is_owner) THEN
    RAISE EXCEPTION '관리자 삭제는 1차 관리자만 할 수 있습니다';
  END IF;
  DELETE FROM public.workers WHERE id = p_worker_id;
  UPDATE public.process_managers SET
    p1_a = public.remove_name_from_list(p1_a, v_name), p1_b = public.remove_name_from_list(p1_b, v_name),
    p2_a = public.remove_name_from_list(p2_a, v_name), p2_b = public.remove_name_from_list(p2_b, v_name),
    p2_c = public.remove_name_from_list(p2_c, v_name),
    p4_a = public.remove_name_from_list(p4_a, v_name), p4_b = public.remove_name_from_list(p4_b, v_name),
    p3_a = public.remove_name_from_list(p3_a, v_name), p3_b = public.remove_name_from_list(p3_b, v_name),
    stage5 = public.remove_name_from_list(stage5, v_name), pk_a = public.remove_name_from_list(pk_a, v_name),
    pk_b = public.remove_name_from_list(pk_b, v_name), updated_at = now()
  WHERE id = 1;
END;
$$;

CREATE OR REPLACE FUNCTION public.admin_set_admin(p_worker_id BIGINT, p_is_admin BOOLEAN)
RETURNS VOID LANGUAGE plpgsql SECURITY DEFINER SET search_path = '' AS $$
DECLARE v_admin BIGINT := public.assert_admin();
BEGIN
  IF NOT EXISTS (SELECT 1 FROM public.workers WHERE id = v_admin AND is_owner) THEN
    RAISE EXCEPTION '관리자 지정·해제는 1차 관리자만 할 수 있습니다';
  END IF;
  IF EXISTS (SELECT 1 FROM public.workers WHERE id = p_worker_id AND is_owner) THEN
    RAISE EXCEPTION '1차 관리자의 권한은 바꿀 수 없습니다';
  END IF;
  UPDATE public.workers SET is_admin = p_is_admin WHERE id = p_worker_id AND status = '사용';
  IF NOT FOUND THEN RAISE EXCEPTION '없는 직원입니다'; END IF;
END;
$$;

