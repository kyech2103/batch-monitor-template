-- 7. 권한 (기본 예시: 등록된 직원으로 로그인한 사용자만 읽고 쓴다)
-- --------------------------------------------------------------------
DO $$
DECLARE t TEXT;
BEGIN
  FOREACH t IN ARRAY ARRAY['batches', 'shelf_data', 'process_managers', 'timeline_logs', 'equipment_templates',
                           'equipment_jobs', 'todo_rules', 'todo_schedules'] LOOP
    EXECUTE format('ALTER TABLE public.%I ENABLE ROW LEVEL SECURITY', t);
    EXECUTE format('DROP POLICY IF EXISTS "workers only" ON public.%I', t);
    EXECUTE format('CREATE POLICY "workers only" ON public.%I FOR ALL TO authenticated
                    USING (public.is_active_worker()) WITH CHECK (public.is_active_worker())', t);
    EXECUTE format('REVOKE ALL ON public.%I FROM anon', t);
  END LOOP;
END $$;

-- 직원 표: 로그인한 직원은 이름 목록만 읽는다(담당자 고르기). 쓰기는 위의 관리자 함수로만
ALTER TABLE public.workers ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS "workers only" ON public.workers;
CREATE POLICY "workers only" ON public.workers FOR SELECT TO authenticated USING (public.is_active_worker());
REVOKE ALL ON public.workers FROM anon, authenticated;
GRANT SELECT (id, name, department, status, is_admin) ON public.workers TO authenticated;

-- 알림·AI 기록 표: 화면에서 직접 읽고 쓰지 않는다 (위 함수와 서버 함수로만)
ALTER TABLE public.push_subscriptions ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.push_log ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.assist_log ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.push_subscriptions, public.push_log, public.assist_log FROM anon, authenticated;

-- 함수 실행 권한: 기본은 막고 필요한 것만 연다
REVOKE EXECUTE ON ALL FUNCTIONS IN SCHEMA public FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.current_worker_id(), public.is_active_worker(),
  public.replace_todo_rules(jsonb, text), public.replace_todo_schedules(jsonb, timestamptz),
  public.register_push_subscription(text, text, text, text), public.unregister_push_subscription(text),
  public.flag_assist_log(bigint), public.admin_list_workers(), public.admin_add_worker(TEXT, TEXT, TEXT),
  public.admin_retire_worker(BIGINT), public.admin_set_admin(BIGINT, BOOLEAN)
  TO authenticated;
GRANT EXECUTE ON FUNCTION public.push_mark_failed(BIGINT, TEXT), public.get_push_config() TO service_role;

