-- 매분: 5분 뒤 시작할 할 일이나 시작·종료한 공정4 작업이 있으면 todo-push 함수를 깨운다
CREATE OR REPLACE FUNCTION public.todo_push_tick() RETURNS VOID
LANGUAGE plpgsql SECURITY DEFINER SET search_path = '' AS $$
DECLARE
  v_now timestamp := now() AT TIME ZONE 'Asia/Seoul';
  v_due BOOLEAN;
BEGIN
  SELECT EXISTS (
    SELECT 1 FROM public.todo_schedules s
    JOIN public.push_subscriptions sub ON sub.worker_id = s.worker_id
    WHERE s.record_type = 'TODO'
      AND s.target_date BETWEEN v_now::date - 1 AND v_now::date + 1
      AND (s.target_date::text || ' ' || s.target_time)::timestamp - interval '5 minutes' BETWEEN v_now - interval '10 minutes' AND v_now
      AND (s.target_date::text || ' ' || s.target_time)::timestamp > v_now
      AND NOT EXISTS (SELECT 1 FROM public.push_log pl
        WHERE pl.subscription_id = sub.id AND pl.target_date = s.target_date AND pl.target_time = s.target_time)
  ) OR EXISTS (
    SELECT 1 FROM public.equipment_jobs j
    WHERE cardinality(j.notify_worker_ids) > 0
      AND ((NOT j.start_push_done AND j.start_at BETWEEN now() - interval '10 minutes' AND now())
        OR (NOT j.end_push_done AND j.end_at BETWEEN now() - interval '10 minutes' AND now()))
  ) INTO v_due;

  IF v_due THEN
    PERFORM net.http_post(
      url := (SELECT decrypted_secret FROM vault.decrypted_secrets WHERE name = 'project_url' LIMIT 1) || '/functions/v1/todo-push',
      headers := jsonb_build_object('Content-Type', 'application/json',
        'x-cron-secret', COALESCE((SELECT decrypted_secret FROM vault.decrypted_secrets WHERE name = 'push_cron_secret' LIMIT 1), '')),
      body := jsonb_build_object('action', 'dispatch'));
  END IF;
END;
$$;

SELECT cron.schedule('todo-push-tick', '* * * * *', 'SELECT public.todo_push_tick();');
SELECT cron.schedule('todo-push-cleanup', '0 4 * * *',
  $$DELETE FROM public.push_log WHERE sent_at < now() - interval '30 days'; DELETE FROM public.push_subscriptions WHERE fail_count >= 5;$$);

