CREATE TABLE IF NOT EXISTS public.push_subscriptions (
  id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  worker_id    BIGINT NOT NULL REFERENCES public.workers(id) ON DELETE CASCADE,
  endpoint     TEXT UNIQUE NOT NULL CHECK (endpoint LIKE 'https://%' AND char_length(endpoint) <= 1024),
  p256dh       TEXT NOT NULL,
  auth         TEXT NOT NULL,
  platform     TEXT NOT NULL CHECK (platform IN ('android', 'ios', 'other')),
  created_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
  last_seen_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  last_error   TEXT,
  fail_count   INT NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS public.push_log (
  id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  subscription_id BIGINT NOT NULL REFERENCES public.push_subscriptions(id) ON DELETE CASCADE,
  worker_id       BIGINT NOT NULL REFERENCES public.workers(id) ON DELETE CASCADE,
  target_date     DATE NOT NULL,
  target_time     TEXT NOT NULL,
  task_count      INT NOT NULL DEFAULT 1,
  sent_at         TIMESTAMPTZ NOT NULL DEFAULT now(),
  status          TEXT NOT NULL DEFAULT 'sent',
  CONSTRAINT uq_push_log_bundle UNIQUE (subscription_id, target_date, target_time)
);

-- 이 기기의 알림 구독을 로그인한 직원에게 등록 (직원 한 명당 최근 기기 3대까지)
CREATE OR REPLACE FUNCTION public.register_push_subscription(p_endpoint text, p_p256dh text, p_auth text, p_platform text)
RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path = '' AS $$
DECLARE v_worker_id BIGINT := public.current_worker_id(); v_sub_id BIGINT;
BEGIN
  IF v_worker_id IS NULL THEN RAISE EXCEPTION '로그인이 필요합니다'; END IF;
  INSERT INTO public.push_subscriptions (worker_id, endpoint, p256dh, auth, platform, last_seen_at, fail_count)
  VALUES (v_worker_id, p_endpoint, p_p256dh, p_auth, p_platform, now(), 0)
  ON CONFLICT (endpoint) DO UPDATE SET worker_id = EXCLUDED.worker_id, p256dh = EXCLUDED.p256dh, auth = EXCLUDED.auth,
    platform = EXCLUDED.platform, last_seen_at = now(), fail_count = 0
  RETURNING id INTO v_sub_id;
  DELETE FROM public.push_subscriptions WHERE worker_id = v_worker_id AND id NOT IN (
    SELECT id FROM public.push_subscriptions WHERE worker_id = v_worker_id ORDER BY last_seen_at DESC LIMIT 3);
  RETURN jsonb_build_object('subscription_id', v_sub_id);
END;
$$;

CREATE OR REPLACE FUNCTION public.unregister_push_subscription(p_endpoint text)
RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path = '' AS $$
BEGIN
  DELETE FROM public.push_subscriptions WHERE endpoint = p_endpoint AND worker_id = public.current_worker_id();
  RETURN jsonb_build_object('ok', true);
END;
$$;

-- 발송 실패 기록 (todo-push 함수가 서비스 키로 부른다)
CREATE OR REPLACE FUNCTION public.push_mark_failed(p_id BIGINT, p_error TEXT)
RETURNS VOID LANGUAGE sql SECURITY DEFINER SET search_path = '' AS $$
  UPDATE public.push_subscriptions SET fail_count = fail_count + 1, last_error = substring(p_error from 1 for 200) WHERE id = p_id;
$$;

