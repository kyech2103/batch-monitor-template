CREATE OR REPLACE FUNCTION public.assert_admin() RETURNS BIGINT
LANGUAGE plpgsql STABLE SECURITY DEFINER SET search_path = '' AS $$
DECLARE v_id BIGINT;
BEGIN
  SELECT w.id INTO v_id FROM public.workers w WHERE w.id = public.current_worker_id() AND w.is_admin;
  IF v_id IS NULL THEN RAISE EXCEPTION '관리자 권한이 없습니다'; END IF;
  RETURN v_id;
END;
$$;

CREATE OR REPLACE FUNCTION public.admin_list_workers()
RETURNS TABLE (id BIGINT, name TEXT, department TEXT, email TEXT, is_admin BOOLEAN, is_owner BOOLEAN)
LANGUAGE plpgsql SECURITY DEFINER SET search_path = '' AS $$
BEGIN
  PERFORM public.assert_admin();
  RETURN QUERY SELECT w.id, w.name, w.department, w.email, w.is_admin, w.is_owner
    FROM public.workers w WHERE w.status = '사용' ORDER BY w.is_owner DESC, w.is_admin DESC, w.name;
END;
$$;

